/** Every file under `dir`, relative and with `/`. */
const filesUnder = (dir) =>
  fs
    .readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) =>
      path.relative(dir, path.join(entry.parentPath, entry.name)).replaceAll('\\', '/'),
    );

/**
 * What keeps each marker (a component's selector) from being lazily loaded in a built
 * application's `dist` folder, one line each. The initial files are the scripts index.html loads
 * or preloads on the first visit; a marker must be in none of them, and in another .js file.
 */
export function lazyChunkProblems({ dist, markers }) {
  const html = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
  const initial = new Set();
  for (const tag of html.matchAll(/<(script|link)\b[^>]*>/g)) {
    if (tag[1] === 'link' && !/\brel=["']?modulepreload\b/.test(tag[0])) continue;
    const value = (tag[1] === 'script' ? /\bsrc=["']?([^"'\s>]+)/ : /\bhref=["']?([^"'\s>]+)/).exec(
      tag[0],
    )?.[1];
    if (value && !/^[a-z]+:/i.test(value)) initial.add(value.replace(/^\.?\//, ''));
  }
  const scripts = filesUnder(dist).filter((file) => file.endsWith('.js'));
  const texts = new Map(
    scripts.map((file) => [file, fs.readFileSync(path.join(dist, file), 'utf8')]),
  );
  const problems = [];
  for (const marker of markers) {
    const holders = scripts.filter((file) => texts.get(file).includes(marker));
    const eager = holders.filter((file) => initial.has(file));
    for (const file of eager)
      problems.push(`${marker} is in ${file}, which index.html loads on the first visit`);
    if (!holders.some((file) => !initial.has(file)))
      problems.push(`${marker} is in no lazy chunk of ${dist}`);
  }
  return problems;
}

/**
 * What keeps the country's text overrides (`fe`/text-overrides/<lang>.json) from reaching a built
 * application's bundles in `dist` (the folder holding niord-app/ and niord-info/), one line each:
 * every override's text must be the value of its key in that language's built bundle.
 */
export function textOverrideProblems({ dist, fe }) {
  const dir = path.join(fe, 'text-overrides');
  if (!fs.existsSync(dir)) return [];
  const problems = [];
  const projects = { admin: 'niord-app', info: 'niord-info' };
  for (const name of fs
    .readdirSync(dir)
    .filter((file) => file.endsWith('.json'))
    .sort()) {
    const lang = name.slice(0, -5);
    const overrides = JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8'));
    for (const [app, project] of Object.entries(projects)) {
      const keys = Object.entries(overrides[app] ?? {});
      if (!keys.length) continue;
      const file = path.join(dist, project, 'browser', 'assets', 'i18n', `${lang}.json`);
      if (!fs.existsSync(file)) {
        problems.push(`${project} has no ${lang} bundle, which text-overrides/${name} overrides`);
        continue;
      }
      const bundle = flatten(JSON.parse(fs.readFileSync(file, 'utf8')));
      for (const [key, { text }] of keys)
        if (bundle[key] !== text)
          problems.push(
            `${key} is ${JSON.stringify(bundle[key] ?? null)} in ${project}'s ${lang} bundle, not the override's ${JSON.stringify(text)}`,
          );
    }
  }
  return problems;
}

const seconds = (start) => `${((Date.now() - start) / 1000).toFixed(1)} s`;

/** Runs one step, printing its name and duration; throws when it fails. */
function step(name, action) {
  const start = Date.now();
  console.log(`example: ${name} …`);
  try {
    action();
  } catch (error) {
    console.error(`example: ${name} FAILED after ${seconds(start)}: ${error.message}`);
    throw Object.assign(new Error(`${name} failed`), { reported: true });
  }
  console.log(`example: ${name} ok, ${seconds(start)}`);
}

/**
 * Runs a command in `cwd`; throws on a non-zero exit unless `allowFailure`. Its output is
 * inherited, or with `capture` collected and echoed when it ends (not with `quiet`, for a probe
 * run again and again). Returns `{ status, output }`,
 * `output` the captured stdout and stderr ('' when inherited).
 */
function run(command, args, { cwd, env, capture = false, allowFailure = false, quiet = false }) {
  const result = spawnSync(command, args, {
    cwd,
    env,
    stdio: capture ? ['inherit', 'pipe', 'pipe'] : 'inherit',
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
    // npm and npx are .cmd files on Windows, which Node starts only through a shell; the
    // arguments are this file's own constants.
    shell: process.platform === 'win32' && (command === 'npm' || command === 'npx'),
  });
  if (result.error) throw result.error;
  if (capture && !quiet) {
    process.stdout.write(result.stdout);
    process.stderr.write(result.stderr);
  }
  if (result.status !== 0 && !allowFailure)
    throw new Error(`${command} ${args.join(' ')} exited ${result.status}`);
  return { status: result.status, output: capture ? `${result.stdout}${result.stderr}` : '' };
}

/** Removes a local image tag of the harness's own; a tag the run never made is reported and left. */
function removeImage(tag) {
  const removed = spawnSync('docker', ['rmi', tag], { stdio: 'inherit', shell: false });
  if (removed.status !== 0) console.error(`example: docker rmi ${tag} did not remove it`);
}

/** Removes a container of the harness's own, running or not; one the run never made is reported. */
function removeContainer(name) {
  const removed = spawnSync('docker', ['rm', '-f', name], { stdio: 'inherit', shell: false });
  if (removed.status !== 0) console.error(`example: docker rm -f ${name} did not remove it`);
}

/** Copies the country's own folders, be/ and fe/, as git sees them (no ignored file), into `target`. */
function copyCountry(source, target) {
  for (const relative of gitFiles(source).filter((file) => /^(be|fe)\//.test(file))) {
    const to = path.join(target, relative);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(path.join(source, relative), to);
  }
}

