/**
 * The environment of the generated backend's build and checks: on Windows `env` with NIORD_HOME
 * the run's own `<work>/niord-home`, written with forward slashes (a Windows NIORD_HOME with
 * backslashes breaks every integration test context, be/docs/potential-errors.md PORT-1);
 * elsewhere `env` as it is.
 */
export function backendEnv(env, { work, platform = process.platform }) {
  if (platform !== 'win32') return env;
  return { ...env, NIORD_HOME: path.resolve(work, 'niord-home').replaceAll('\\', '/') };
}

const GIT_BASH = 'C:/Program Files/Git/bin/bash.exe';

/**
 * The bash the generated country's checks run under: NIORD_BASH when set, otherwise on Windows
 * Git's own (`bash` there may resolve to WSL's launcher in System32), otherwise `bash` on PATH;
 * fe/scripts/workflow-step.mjs's rule, which the kit's harness does not import.
 */
export function bashPath({
  env = process.env,
  platform = process.platform,
  exists = fs.existsSync,
} = {}) {
  if (env.NIORD_BASH) return env.NIORD_BASH;
  if (platform !== 'win32') return 'bash';
  if (!exists(GIT_BASH)) throw new Error(`Git Bash is not at ${GIT_BASH}: set NIORD_BASH`);
  return GIT_BASH;
}

/**
 * A Maven runner over the scratch repository's arguments `repository`: `(be, args, { env })`
 * runs `<be>/mvnw` with `args` and then `repository` (lib/maven.mjs runMaven, or `runner`), and
 * throws when Maven exits non-zero.
 */
export function mavenRunner(repository, runner = runMaven) {
  return (be, args, { env } = {}) => {
    const status = runner({ be, args: [...args, ...repository], paths: repository, env });
    if (status !== 0) throw new Error(`Maven exited ${status}`);
  };
}

/**
 * The harness's command line: `{ work, mavenRepo, image, withDeps, upgradeFrom, upgradeKitFrom,
 * backend, skipFrontend }`. Throws on anything else.
 */
export function parseArgs(args) {
  const options = {
    mavenRepo: path.join(os.homedir(), '.m2', 'repository'),
    image: false,
    withDeps: false,
    backend: false,
    skipFrontend: false,
  };
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--work' && args[i + 1]) options.work = path.resolve(args[++i]);
    else if (args[i] === '--maven-repo' && args[i + 1]) options.mavenRepo = path.resolve(args[++i]);
    else if (args[i] === '--image') options.image = true;
    else if (args[i] === '--with-deps') options.withDeps = true;
    else if (args[i] === '--backend') options.backend = true;
    else if (args[i] === '--skip-frontend') options.skipFrontend = true;
    else if (args[i] === '--upgrade-from') {
      const value = args[++i];
      if (!value || value.startsWith('--'))
        throw new Error('--upgrade-from needs the previous published niord-fe-src zip');
      options.upgradeFrom = path.resolve(value);
    } else if (args[i] === '--upgrade-kit-from') {
      const value = args[++i];
      if (!value || value.startsWith('--'))
        throw new Error('--upgrade-kit-from needs the previous published niord-country-kit zip');
      options.upgradeKitFrom = path.resolve(value);
    } else throw new Error(`unknown argument "${args[i]}" (${USAGE})`);
  }
  if (options.skipFrontend && !options.backend)
    throw new Error(
      '--skip-frontend leaves only init, set-up and the backend steps, so it comes with --backend',
    );
  if (options.skipFrontend && (options.image || options.withDeps || options.upgradeFrom))
    throw new Error(
      '--skip-frontend runs no frontend step: --image/--upgrade-from are frontend steps',
    );
  if (options.withDeps && !options.image)
    throw new Error('--with-deps installs what the image checks need, so it comes with --image');
  if (options.upgradeKitFrom && !options.upgradeFrom)
    throw new Error(
      '--upgrade-kit-from comes with --upgrade-from: it is the kit package of the same release',
    );
  if (!options.work)
    throw new Error('--work <dir> is required: the folder the example is set up in');
  // The first two reach the example's set-up in MAVEN_ARGS, which the Maven wrapper splits on
  // whitespace and, on Windows, hands to cmd.exe unquoted; the previous zip and kit package are
  // installed by Maven as the first ones are, and held to the same rule.
  for (const [flag, value] of [
    ['--work', options.work],
    ['--maven-repo', options.mavenRepo],
    ...(options.upgradeFrom ? [['--upgrade-from', options.upgradeFrom]] : []),
    ...(options.upgradeKitFrom ? [['--upgrade-kit-from', options.upgradeKitFrom]] : []),
  ])
    if (/[\s"%^&|<>!]/.test(value))
      throw new Error(
        `${flag} ${value} has a space or a character cmd.exe reads: it reaches Maven in MAVEN_ARGS, which is split on whitespace; pass a path without one`,
      );
  // The zip is built from the working tree's fe/ and country-kit/: a work folder inside either would
  // be packed into the next zip and read by the guards.
  for (const [label, folder] of [
    ['fe/', FE],
    ['country-kit/', KIT],
  ]) {
    const inside = path.relative(folder, options.work);
    if (!inside.startsWith('..') && !path.isAbsolute(inside))
      throw new Error(
        `--work ${options.work} is inside the base product's ${label}; the example is set up outside the tree`,
      );
  }
  for (const [flag, file] of [
    ['--upgrade-from', options.upgradeFrom],
    ['--upgrade-kit-from', options.upgradeKitFrom],
  ])
    if (file && !fs.statSync(file, { throwIfNoEntry: false })?.isFile())
      throw new Error(`${flag} ${file} is not a file`);
  return options;
}

/** The entries of the zip `file` (bytes `zip`) given with `flag`; throws naming both. */
function entriesOf(flag, file, zip) {
  try {
    return readZip(zip);
  } catch (error) {
    throw new Error(`${flag} ${file}: ${error.message}`, { cause: error });
  }
}

/** The `version` of the JSON entry `name` among `entries`, undefined when there is none. */
function versionIn(entries, name) {
  const entry = entries.find((found) => found.name === name);
  return entry && JSON.parse(entry.data.toString('utf8')).version;
}

/**
 * The previous published zip --upgrade-from names: `{ version, zip, sha256 }`, its version from
 * its catalog.json. Throws when it is not a source zip, names a version the harness makes, or is
 * from before the kit package: its kit still inside it, the kit's example country-kit/example/be/
 * among its entries.
 */
export function previousZip(file) {
  const zip = fs.readFileSync(file);
  const entries = entriesOf('--upgrade-from', file, zip);
  let version;
  try {
    version = versionIn(entries, 'catalog.json');
  } catch (error) {
    throw new Error(`--upgrade-from ${file}: ${error.message}`, { cause: error });
  }
  if (typeof version !== 'string' || !PLAIN_VERSION.test(version))
    throw new Error(`--upgrade-from ${file} has no catalog.json naming its version`);
  if (version === VERSION || version === NEXT_VERSION)
    throw new Error(`--upgrade-from ${file} is version ${version}, which the harness makes itself`);
  if (entries.some(({ name }) => name.startsWith('country-kit/example/be/')))
    throw new Error(
      `--upgrade-from ${file} is the niord-fe-src of ${version}, from before the kit package: an upgrade test starts at 4.0.109 or later`,
    );
  return { version, zip, sha256: hashOf(zip) };
}

/**
 * The previous published kit package --upgrade-kit-from names, of the release whose zip is of
 * `version`: `{ version, zip, sha256 }`, its version from its marker (kit.json). Throws when it has
 * no marker naming a version, or names another version than the zip's.
 */
export function previousKitZip(file, version) {
  const zip = fs.readFileSync(file);
  const entries = entriesOf('--upgrade-kit-from', file, zip);
  let found;
  try {
    found = versionIn(entries, MARKER);
  } catch (error) {
    throw new Error(`--upgrade-kit-from ${file}: ${MARKER}: ${error.message}`, { cause: error });
  }
  if (typeof found !== 'string' || !PLAIN_VERSION.test(found))
    throw new Error(
      `--upgrade-kit-from ${file} has no ${MARKER} naming its version: it is not a kit package`,
    );
  if (found !== version)
    throw new Error(
      `--upgrade-kit-from ${file} is the kit package of ${found}, not of ${version}, the version of the --upgrade-from zip`,
    );
  return { version, zip, sha256: hashOf(zip) };
}

/**
 * The harness. `docker` is the probe --backend asks before anything is made (probeDocker; a test
 * passes its own).
 */
export function main(args, { docker = probeDocker } = {}) {
  const { work, mavenRepo, image, withDeps, upgradeFrom, upgradeKitFrom, backend, skipFrontend } =
    parseArgs(args);
  if (backend) {
    const refusal = dockerRefusal(docker());
    if (refusal) throw new Error(refusal);
  }
  // Asked first too, so a missing Git Bash stops the run before anything is built.
  const bash = backend ? bashPath() : undefined;
  const previous = upgradeFrom ? previousZip(upgradeFrom) : undefined;
  if (previous && !upgradeKitFrom)
    throw new Error(
      `--upgrade-from ${upgradeFrom} is the niord-fe-src of ${previous.version}: give its kit package, that release's niord-country-kit, with --upgrade-kit-from`,
    );
  const previousKit = previous ? previousKitZip(upgradeKitFrom, previous.version) : undefined;
  const started = Date.now();
  const m2 = path.join(work, 'm2');
  const zip = path.join(work, `niord-fe-src-${VERSION}.zip`);
  const kitFile = path.join(work, `niord-country-kit-${VERSION}.zip`);
  const country = path.join(work, 'xx');
  const repository = [`-Dmaven.repo.local=${m2}`, `-Dmaven.repo.local.tail=${mavenRepo}`];
  const maven = mavenRunner(repository);
  let sha256;
  let bytes;
  let kitSha256;
  let kitBytes;

  /** Installs one file into the scratch repository as `<groupId>:<artifactId>:<version>:zip`. */
  const installFile = (file, groupId, artifactId, version) => {
    const status = runMaven({
      be: BE,
      args: [
        '-B',
        '-N',
        '-ntp',
        'install:install-file',
        `-Dfile=${file}`,
        `-DgroupId=${groupId}`,
        `-DartifactId=${artifactId}`,
        `-Dversion=${version}`,
        '-Dpackaging=zip',
        ...repository,
      ],
      paths: [`-Dfile=${file}`, ...repository],
    });
    if (status !== 0) throw new Error(`Maven exited ${status}`);
  };

  /**
   * Installs a source zip `feSrc` as niord-fe-src, the kit package `kit` as niord-country-kit and
   * the base product's niord-parent, all as `version`.
   */
  const install = ({ feSrc, kit, version }) => {
    step(`install the zip ${version} and its kit package into the scratch Maven repository`, () => {
      installFile(feSrc, 'org.niord.web', 'niord-fe-src', version);
      installFile(kit, 'org.niord', 'niord-country-kit', version);
    });
    step(`install niord-parent ${version} into the scratch Maven repository`, () =>
      maven(BE, ['-B', '-N', '-ntp', `-Drevision=${version}`, 'install']),
    );
  };

  step(
    `build the source zip and the kit package ${VERSION} from the working tree, checked as publishing checks them`,
    () => {
      fs.mkdirSync(work, { recursive: true });
      // The scratch repository holds only this run's versions of both, so `latest-catalog` and
      // `prune --base` read the example's two and set-up fetches no earlier run's kit.
      for (const folder of [
        ['org', 'niord', 'web', 'niord-fe-src'],
        ['org', 'niord', 'niord-country-kit'],
      ])
        fs.rmSync(path.join(m2, ...folder), { recursive: true, force: true });
      // kit:zip's and kit:package's builds, the ones the publish workflow runs: each writes
      // nothing when a check fails.
      const built = writeSourceZip({ fe: FE, version: VERSION, out: zip });
      if (built.problems.length) throw new Error(built.problems.join('; '));
      ({ zip: bytes, sha256 } = built);
      console.log(`example: ${path.basename(zip)}, ${built.zip.length} bytes, sha256 ${sha256}`);
      const kit = writeKitZip({ version: VERSION, out: kitFile });
      if (kit.problems.length) throw new Error(kit.problems.join('; '));
      ({ zip: kitBytes, sha256: kitSha256 } = kit);
      console.log(
        `example: ${path.basename(kitFile)}, ${kit.zip.length} bytes, sha256 ${kitSha256}`,
      );
    },
  );
  install({ feSrc: zip, kit: kitFile, version: VERSION });

  const fe = path.join(country, 'fe');
  const env = { ...process.env, MAVEN_ARGS: [...repository, '-ntp'].join(' ') };
  for (const name of Object.keys(env))
    if (name === 'NIORD_BASE' || name.startsWith('NIORD_PACK_')) delete env[name];
  const catalog = path.join(work, 'latest-catalog.json');
  const latest = (version) =>
    step(
      `node ../.niord/kit/pack.mjs latest-catalog: ${version}, the newest in the scratch repository`,
      () => {
        const { output } = run(
          process.execPath,
          [path.join('..', '.niord', 'kit', 'pack.mjs'), 'latest-catalog', '--out', catalog],
          { cwd: fe, env, capture: true },
        );
        if (!new RegExp(`^latest-catalog: ${version.replaceAll('.', '[.]')}$`, 'm').test(output))
          throw new Error(`latest-catalog did not name ${version}`);
        if (JSON.parse(fs.readFileSync(catalog, 'utf8')).version !== version)
          throw new Error(`${catalog} is not the catalog of ${version}`);
      },
    );

  // The example country xx; --skip-frontend runs none of it, only the untouched country's init,
  // set-up and backend.
  if (!skipFrontend) {
    step(`copy the example to ${country}`, () => {
      fs.rmSync(country, { recursive: true, force: true });
      copyCountry(EXAMPLE, country);
      copyWrapper(path.join(country, 'be'));
      const { counts } = pseudoLocalise({
        fe: FE,
        be: BE,
        out: path.join(country, 'fe', 'packs', 'zz'),
        index: path.join(country, 'fe', 'info', 'app', 'index.html'),
      });
      console.log(
        `example: pack zz generated, ${Object.values(counts).reduce((a, b) => a + b, 0)} texts`,
      );
      fs.writeFileSync(
        path.join(country, 'fe', 'niord-pins.lock.json'),
        lockText({ version: VERSION, sha256, kit: { sha256: kitSha256 } }),
      );
    });
    step('node setup.mjs', () => run(process.execPath, ['setup.mjs'], { cwd: fe, env }));
    // The pack tools in a country workspace, as the kit's README gives the command: the home pack
    // zz against the pinned zip's catalog, which it matches, so nothing is removed or written.
    step('node ../.niord/kit/pack.mjs prune zz: the home pack, nothing to remove', () => {
      const { output } = run(
        process.execPath,
        [path.join('..', '.niord', 'kit', 'pack.mjs'), 'prune', 'zz'],
        { cwd: fe, env, capture: true },
      );
      if (!/^pack prune: 0 key\(s\) removed; nothing written$/m.test(output))
        throw new Error('pack prune zz did not run on packs/zz/ with nothing to remove');
    });
    step(
      ".niord/packs/zz/ holds exactly zz's canonical archive, as set-up stages every pack",
      () => {
        const problems = stagedPackProblems(fe, 'zz');
        if (problems.length) throw new Error(problems.join('; '));
      },
    );
    latest(VERSION);
    step('npm ci', () =>
      run('npm', ['ci', '--prefer-offline', '--no-audit', '--no-fund'], { cwd: fe, env }),
    );
    step('npm run build', () => run('npm', ['run', 'build'], { cwd: fe, env }));
    step('the country pages and slot components are lazy chunks', () => {
      const problems = Object.entries(LAZY_MARKERS).flatMap(([project, markers]) =>
        lazyChunkProblems({ dist: path.join(fe, 'dist', project, 'browser'), markers }),
      );
      if (problems.length) throw new Error(problems.join('; '));
    });
    step("the country's text overrides are in the built bundles", () => {
      const problems = textOverrideProblems({ dist: path.join(fe, 'dist'), fe });
      if (problems.length) throw new Error(problems.join('; '));
    });
    step('npm test', () => run('npm', ['test'], { cwd: fe, env }));
    step('npm run lint', () => run('npm', ['run', 'lint'], { cwd: fe, env }));
    if (image) {
      step('Chromium for the image checks', () =>
        run(
          'npx',
          [
            'playwright',
            'install',
            '--only-shell',
            ...(withDeps ? ['--with-deps'] : []),
            'chromium',
          ],
          { cwd: fe, env },
        ),
      );
      try {
        step('the public-site image', () =>
          run('npm', ['run', 'image:info', '--', '--tag', IMAGE_TAG], { cwd: fe, env }),
        );
      } finally {
        removeImage(IMAGE_TAG);
      }
    }
    step("the example's e2e spec lists with the generated Playwright configuration", () => {
      const { output } = run('npx', ['playwright', 'test', '--list'], {
        cwd: fe,
        env,
        capture: true,
      });
      if (!/harbour.spec.ts/.test(output)) throw new Error('e2e/harbour.spec.ts is not listed');
    });
  }

  const harness = {
    step,
    run,
    env,
    image,
    removeImage,
    removeContainer,
    backend,
    skipFrontend,
    m2,
    maven,
    ...(backend ? { bash } : {}),
    backendEnv: backendEnv(env, { work }),
  };
  // init, set-up, the backend with --backend, the frontend steps, then publishing and pinning.
  const published = untouched({
    work,
    zip: bytes,
    sha256,
    kitZip: kitBytes,
    kitSha256,
    version: VERSION,
    country,
    catalog,
    h: harness,
  });
  if (published) console.log(published);
  const summary = [...(published ? [published] : []), backend ? BACKEND_BUILT : BACKEND_SKIPPED];

  if (!skipFrontend) {
    const next = path.join(work, `niord-fe-src-${NEXT_VERSION}.zip`);
    const nextKit = path.join(work, `niord-country-kit-${NEXT_VERSION}.zip`);
    let fixture;
    step(`derive the fixture zip and kit package ${NEXT_VERSION} from ${VERSION}'s`, () => {
      const derived = fixtureZip(bytes);
      const kit = fixtureKitZip(kitBytes);
      const problems = [...verifySourceZip(derived.zip), ...verifyKitZip(kit.zip)];
      if (problems.length) throw new Error(problems.join('; '));
      fixture = { version: NEXT_VERSION, ...derived, kitZip: kit.zip, kitSha256: kit.sha256 };
      fs.writeFileSync(next, fixture.zip);
      fs.writeFileSync(nextKit, fixture.kitZip);
      console.log(`example: ${path.basename(next)}, sha256 ${fixture.sha256}`);
      console.log(`example: ${path.basename(nextKit)}, sha256 ${fixture.kitSha256}`);
    });
    install({ feSrc: next, kit: nextKit, version: NEXT_VERSION });
    summary.push(
      fixtureUpgrade({
        country,
        from: { version: VERSION },
        to: fixture,
        work,
        h: harness,
      }),
    );
    latest(NEXT_VERSION);
    step(
      `node ../.niord/kit/pack.mjs prune zz --base ${VERSION}: both example versions read, nothing to remove`,
      () => {
        const { output } = run(
          process.execPath,
          [path.join('..', '.niord', 'kit', 'pack.mjs'), 'prune', 'zz', '--base', VERSION],
          { cwd: fe, env, capture: true },
        );
        if (!output.includes(`pack prune: the catalogs of ${VERSION}, ${NEXT_VERSION} read`))
          throw new Error(`prune --base did not read ${VERSION} and ${NEXT_VERSION}`);
        if (!/^pack prune: 0 key\(s\) removed; nothing written$/m.test(output))
          throw new Error('prune --base removed a key, or wrote a file');
      },
    );

    if (previous) {
      const file = path.join(work, `niord-fe-src-${previous.version}.zip`);
      fs.writeFileSync(file, previous.zip);
      const kit = path.join(work, `niord-country-kit-${previous.version}.zip`);
      fs.writeFileSync(kit, previousKit.zip);
      install({ feSrc: file, kit, version: previous.version });
      summary.push(
        upgradeTest({
          from: { ...previous, kitZip: previousKit.zip, kitSha256: previousKit.sha256 },
          to: { version: VERSION, zip: bytes, sha256, kitZip: kitBytes, kitSha256 },
          work,
          h: harness,
        }),
      );
    } else summary.push(SKIPPED);
  }
  for (const line of summary) console.log(line);
  writeStepSummary(summary);
  console.log(
    skipFrontend
      ? `example: init, set-up and the generated backend green in ${seconds(started)}`
      : `example: the example country set up, built, tested and linted${image ? ', its image built and checked' : ''}, the untouched init${backend ? ', its backend' : ''} and the fixture upgrade green${previous ? ', the upgrade test passed,' : ''} in ${seconds(started)}`,
  );
}

const invokedDirectly =
  process.argv[1] !== undefined &&
  fs.realpathSync(path.resolve(process.argv[1])) ===
    fs.realpathSync(fileURLToPath(import.meta.url));

if (invokedDirectly) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    if (!error.reported) console.error(`example: ${error.message}`);
    process.exit(1);
  }
}
