/**
 * Why --backend cannot run, from the result of `docker info --format {{.ServerVersion}}`
 * (spawnSync's): undefined when Docker answered, otherwise the refusal.
 */
export function dockerRefusal(result) {
  if (!result.error && result.status === 0) return undefined;
  const how = result.error
    ? `could not be run: ${result.error.message}`
    : `failed with exit ${result.status}`;
  return `--backend builds yy's backend with its integration tests on Testcontainers, which need Docker: docker info ${how}; start Docker, or run without --backend`;
}

