/**
 * The generated language configuration of a country workspace, one per application, in place of
 * the base product's `country-specific/default/language.config.ts`. It is data: the values go
 * into `language.config.json`, and a constant TypeScript file beside it imports that JSON and
 * exports it as `COUNTRY_LANGUAGES` with the application's type. No manifest or pack value is ever
 * written into source text.
 *
 *   administration app   availableLanguages   every UI and content language, in the content
 *                                             languages' order (the canonical model-language
 *                                             order), each with its label, locale and flag
 *                        uiLanguages, siteLanguages   the UI languages
 *                        modelLanguages       the content languages
 *                        brandingLanguages    the UI languages the country ships branding for
 *                        defaultLanguage
 *   public site          languages            the UI languages, each with its label, locale, flag
 *                        siteLanguages        the UI languages
 *                        brandingLanguages, defaultLanguage
 *
 * A language's label is its pack's `pack.json` label; its locale is the manifest's `locales`
 * entry, else the pack's; its flag is the one staging ships, `assets/img/flags/<lang>.png`.
 */

/** The TypeScript beside each application's JSON: constant text, the same for every country. */
export const SHIMS = {
  admin: `// Generated by the country kit: the build's languages, from language.config.json beside it.
import type { LanguageConfig } from '@niord/admin/api';
import languages from './language.config.json';

export const COUNTRY_LANGUAGES: LanguageConfig = languages;
`,
  info: `// Generated by the country kit: the build's languages, from language.config.json beside it.
import type { LanguageConfig } from '@niord/info/api';
import languages from './language.config.json';

export const COUNTRY_LANGUAGES: LanguageConfig = languages;
`,
};

/** One language's entry: its label, locale and flag. */
function option(lang, { packs, locales }) {
  const pack = packs[lang];
  if (!pack) throw new Error(`no pack.json read for ${lang}`);
  return {
    value: lang,
    label: pack.label,
    locale: locales?.[lang] ?? pack.locale,
    flagPath: `assets/img/flags/${lang}.png`,
  };
}

/**
 * Both applications' language configurations. `packs` maps each language to its pack.json
 * (`{ label, locale }`); `branding` maps each application to the languages it ships branding for.
 */
export function languageConfigs({ manifest, packs, branding = {} }) {
  const admin = manifest.apps.admin;
  const info = manifest.apps.info;
  const context = { packs, locales: manifest.locales ?? {} };
  const adminLanguages = [
    ...admin.contentLanguages,
    ...admin.uiLanguages.filter((lang) => !admin.contentLanguages.includes(lang)),
  ];
  return {
    admin: {
      availableLanguages: adminLanguages.map((lang) => option(lang, context)),
      uiLanguages: [...admin.uiLanguages],
      brandingLanguages: admin.uiLanguages.filter((lang) => (branding.admin ?? []).includes(lang)),
      defaultLanguage: admin.defaultLanguage,
      siteLanguages: [...admin.uiLanguages],
      modelLanguages: [...admin.contentLanguages],
    },
    info: {
      languages: info.uiLanguages.map((lang) => option(lang, context)),
      siteLanguages: [...info.uiLanguages],
      defaultLanguage: info.defaultLanguage,
      brandingLanguages: info.uiLanguages.filter((lang) => (branding.info ?? []).includes(lang)),
    },
  };
}
