package org.niord.core.script;

import org.niord.core.defaults.DefaultTexts;
import org.niord.core.dictionary.DictionaryService;
import org.niord.core.script.vo.ScriptResourceVo;
import org.niord.core.util.JsonUtils;
import tools.jackson.core.type.TypeReference;
import tools.jackson.core.util.DefaultIndenter;
import tools.jackson.core.util.DefaultPrettyPrinter;
import tools.jackson.core.util.Separators;
import tools.jackson.databind.ObjectMapper;
import tools.jackson.databind.json.JsonMapper;
import tools.jackson.databind.node.ArrayNode;
import tools.jackson.databind.node.ObjectNode;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.net.MalformedURLException;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * Makes the base product's generated release files (docs/code-data-config-plan.md §4.6, §6.4, §6.6), so that none is
 * edited by hand:
 * <ul>
 *   <li>{@code bootstrap/texts.json}: the base product texts as a dictionary import file, in the format the
 *       dictionary import reads (a list of {@code ExportedDictionaryVo}): the five dictionaries of
 *       {@code defaults/base/texts/en/}, language {@code en}, read with the reader start-up uses
 *       ({@link DefaultTexts}). The bootstrap never applies it; a sysadmin imports it to restore a key;</li>
 *   <li>{@code src/main/resources/META-INF/niord/expected-template-paths.txt}: the sorted path names of
 *       {@code bootstrap/templates/} and of every release folder's {@code script-resources.json}, which the
 *       missing-path report reads from the jar (names only: no template is in any jar);</li>
 *   <li>a new release folder {@code bootstrap/releases/<yyyy-mm-dd>-<topic>/}, with {@code -D}{@value #RELEASE_PROPERTY}:
 *       its {@code script-resources.json} (every file of {@code bootstrap/templates/}, in the export format the
 *       script-resource import reads: type by extension, path {@code templates/<path in the folder>}, content, no
 *       id), {@code texts.json} (the texts at this release) and {@code missing-paths.sql} (the missing-path report as
 *       read-only SQL for the release notes, {@link MissingPathReport#sql}). A folder that exists is refused: a
 *       release folder never changes once merged into main. Its {@code README.md} is written by hand.</li>
 * </ul>
 * Contents are written with LF line ends whatever the checkout has, so the files are the same on every machine.
 * {@link ReleaseFilesCurrentTest} runs it.
 */
final class ReleaseFilesGenerator {

    /** {@code -Dniord.releaseFiles.write=true} writes the files instead of checking them */
    static final String WRITE_PROPERTY = "niord.releaseFiles.write";
    /** {@code -Dniord.release=<yyyy-mm-dd>-<topic>} also creates that release folder */
    static final String RELEASE_PROPERTY = "niord.release";

    static final Path BOOTSTRAP = Path.of("bootstrap");
    static final Path TEMPLATES = BOOTSTRAP.resolve("templates");
    static final Path RELEASES = BOOTSTRAP.resolve("releases");
    static final Path TEXTS = BOOTSTRAP.resolve("texts.json");
    static final Path EXPECTED_PATHS = Path.of("src/main/resources").resolve(MissingPathReport.EXPECTED_PATHS);
    static final Path BASE_RESOURCES = Path.of("src/main/resources");

    static final String SCRIPT_RESOURCES_FILE = "script-resources.json";
    static final String TEXTS_FILE = "texts.json";
    static final String MISSING_PATHS_FILE = "missing-paths.sql";
    static final String README_FILE = "README.md";

    /** A release folder's name */
    static final Pattern RELEASE_NAME = Pattern.compile("\\d{4}-\\d{2}-\\d{2}-[a-z0-9]+(-[a-z0-9]+)*");

    /** The one line a placeholder template holds (§6.4) */
    static final String PLACEHOLDER = "<#-- introduction: this deployment's text goes here -->";

    /** The header of the expected-paths list; the report skips lines starting with '#' */
    static final String EXPECTED_PATHS_HEADER = "# Generated by ReleaseFilesGenerator from bootstrap/templates/ and "
            + "bootstrap/releases/*/script-resources.json; never edited. Path names only.\n";

    private static final ObjectMapper MAPPER = JsonMapper.builderWithJackson2Defaults().build();
    private static final DefaultIndenter LF_INDENTER = new DefaultIndenter("  ", "\n");
    private static final DefaultPrettyPrinter PRETTY_PRINTER = new DefaultPrettyPrinter(
            Separators.createDefaultInstance().withObjectNameValueSpacing(Separators.Spacing.AFTER))
            .withObjectIndenter(LF_INDENTER)
            .withArrayIndenter(LF_INDENTER);

    private ReleaseFilesGenerator() {
    }

    /** Returns the text with LF line ends */
    static String lf(String text) {
        return text.replace("\r\n", "\n");
    }

    /**
     * Returns the script-resource import file of a templates folder: one entry a file, sorted by path
     *
     * @param templates the templates folder
     * @return the file's text
     */
    static String scriptResources(Path templates) {
        ArrayNode root = MAPPER.createArrayNode();
        BootstrapTemplates.read(templates).forEach((path, content) -> {
            ObjectNode node = root.addObject();
            node.put("type", ScriptResource.path2type(path).name());
            node.put("path", path);
            node.put("content", lf(content));
        });
        return write(root);
    }

    /**
     * Returns the base product texts as a dictionary import file: the dictionaries in start-up's order, the keys
     * sorted, each with its English value
     *
     * @return the file's text
     */
    static String texts() {
        DefaultTexts.Layered layered;
        try (URLClassLoader cl = new URLClassLoader(new URL[] {BASE_RESOURCES.toUri().toURL()}, null)) {
            layered = DefaultTexts.read(cl, DictionaryService.DEFAULT_BUNDLES, new String[] {DefaultTexts.BASE_LANGUAGE},
                    DefaultTexts.BASE_LANGUAGE);
        } catch (MalformedURLException e) {
            throw new IllegalStateException(e);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        ArrayNode root = MAPPER.createArrayNode();
        for (String bundle : DictionaryService.DEFAULT_BUNDLES) {
            ObjectNode dictionary = root.addObject();
            dictionary.put("name", bundle);
            ArrayNode entries = dictionary.putArray("entries");
            layered.texts(bundle, DefaultTexts.BASE_LANGUAGE).forEach((key, text) -> {
                ObjectNode entry = entries.addObject();
                entry.put("key", key);
                ObjectNode desc = entry.putArray("descs").addObject();
                desc.put("lang", DefaultTexts.BASE_LANGUAGE);
                desc.put("value", lf(text.value()));
            });
        }
        return write(root);
    }

    /**
     * Returns the expected-paths list: the paths of the templates folder and of every release folder's
     * script-resource file, sorted, one a line, after the header
     *
     * @param templates the templates folder
     * @param releases  the releases folder
     * @return the file's text
     */
    static String expectedPaths(Path templates, Path releases) {
        StringBuilder text = new StringBuilder(EXPECTED_PATHS_HEADER);
        expectedPathSet(templates, releases).forEach(path -> text.append(path).append('\n'));
        return text.toString();
    }

    /** The expected paths, sorted */
    static Set<String> expectedPathSet(Path templates, Path releases) {
        Set<String> paths = new TreeSet<>(BootstrapTemplates.read(templates).keySet());
        for (Path folder : releaseFolders(releases)) {
            Path file = folder.resolve(SCRIPT_RESOURCES_FILE);
            if (Files.isRegularFile(file)) {
                readScriptResources(file).forEach(r -> paths.add(r.getPath()));
            }
        }
        return paths;
    }

    /**
     * Creates a release folder with its three generated files
     *
     * @param releases the releases folder
     * @param name     the release folder's name
     * @return the folder
     */
    static Path createRelease(Path releases, String name) {
        if (!RELEASE_NAME.matcher(name).matches()) {
            throw new IllegalArgumentException("A release folder is named <yyyy-mm-dd>-<topic>, in lower case: " + name);
        }
        Path folder = releases.resolve(name);
        if (Files.exists(folder)) {
            throw new IllegalStateException(folder + " exists, and a release folder never changes once it is merged "
                    + "into main: name a new one");
        }
        try {
            Files.createDirectories(folder);
            Files.writeString(folder.resolve(SCRIPT_RESOURCES_FILE), scriptResources(TEMPLATES), StandardCharsets.UTF_8);
            Files.writeString(folder.resolve(TEXTS_FILE), texts(), StandardCharsets.UTF_8);
            List<String> expected = List.copyOf(expectedPathSet(TEMPLATES, releases));
            Files.writeString(folder.resolve(MISSING_PATHS_FILE), MissingPathReport.sql(expected),
                    StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot write " + folder, e);
        }
        return folder;
    }

    /** The release folders, sorted by name */
    static List<Path> releaseFolders(Path releases) {
        if (!Files.isDirectory(releases)) {
            return List.of();
        }
        try (Stream<Path> folders = Files.list(releases)) {
            return folders.filter(Files::isDirectory).sorted().toList();
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot list " + releases, e);
        }
    }

    /** Reads a script-resource import file */
    static List<ScriptResourceVo> readScriptResources(Path file) {
        try {
            return JsonUtils.fromJson(Files.readString(file, StandardCharsets.UTF_8),
                    new TypeReference<List<ScriptResourceVo>>() {});
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot read " + file, e);
        }
    }

    /** Writes the files that are regenerated: the texts and the expected paths */
    static void writeCurrentFiles() {
        try {
            Files.writeString(TEXTS, texts(), StandardCharsets.UTF_8);
            Files.createDirectories(EXPECTED_PATHS.getParent());
            Files.writeString(EXPECTED_PATHS, expectedPaths(TEMPLATES, RELEASES), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot write the release files", e);
        }
    }

    /** The current files and their generated texts, by file */
    static Map<Path, String> currentFiles() {
        return Map.of(TEXTS, texts(), EXPECTED_PATHS, expectedPaths(TEMPLATES, RELEASES));
    }

    private static String write(Object tree) {
        return MAPPER.writer().with(PRETTY_PRINTER).writeValueAsString(tree) + "\n";
    }
}
